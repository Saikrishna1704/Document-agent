
import re
from pathlib import Path

from docx import Document
from docx.shared import Inches, Pt, RGBColor


OUTPUT_DIR = Path(__file__).resolve().parent.parent / "generated"
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)


def add_formatted_paragraph(doc, text: str, style=None):
    """Convert simple Markdown bold and italic markers into Word runs."""
    paragraph = doc.add_paragraph(style=style)

    # Recognize **bold**, *italic*, and plain text.
    pattern = re.compile(r"(\*\*.+?\*\*|\*.+?\*)")
    position = 0

    for match in pattern.finditer(text):
        if match.start() > position:
            paragraph.add_run(text[position:match.start()])

        token = match.group()

        if token.startswith("**"):
            run = paragraph.add_run(token[2:-2])
            run.bold = True
        else:
            run = paragraph.add_run(token[1:-1])
            run.italic = True

        position = match.end()

    if position < len(text):
        paragraph.add_run(text[position:])

    return paragraph


def create_document(
    title: str,
    sections: list[dict],
    document_id: str,
) -> str:
    """Create a professionally formatted Word document."""

    file_path = OUTPUT_DIR / f"{document_id}.docx"

    doc = Document()
    doc.core_properties.title = title
    doc.core_properties.subject = "Business document generated by DocuPilot"

    # Set readable document defaults.
    styles = doc.styles
    styles["Normal"].font.name = "Aptos"
    styles["Normal"].font.size = Pt(10)
    styles["Normal"].font.color.rgb = RGBColor(45, 45, 45)

    doc.add_heading(title, level=0)

    for section in sections:
        heading = section["heading"].strip()
        content = section["content"]

        doc.add_heading(heading, level=1)

        if isinstance(content, str):
            lines = content.splitlines()

            for line in lines:
                line = line.strip()

                if not line:
                    continue

                if line.startswith("### "):
                    doc.add_heading(line[4:].strip(), level=2)
                elif line.startswith("## "):
                    doc.add_heading(line[3:].strip(), level=2)
                elif line.startswith(("- ", "* ")):
                    add_formatted_paragraph(
                        doc,
                        line[2:].strip(),
                        style="List Bullet",
                    )
                elif re.match(r"^\d+[.)]\s+", line):
                    item = re.sub(r"^\d+[.)]\s+", "", line)
                    add_formatted_paragraph(
                        doc,
                        item,
                        style="List Number",
                    )
                else:
                    add_formatted_paragraph(doc, line)

        elif isinstance(content, list):
            for item in content:
                if isinstance(item, str):
                    add_formatted_paragraph(doc, item)

                elif isinstance(item, dict):
                    text = item.get("text", "")
                    style = (
                        "List Bullet"
                        if item.get("bullet", False)
                        else None
                    )
                    add_formatted_paragraph(doc, text, style=style)

    doc.save(file_path)

    return str(file_path)
